/* Regression checks for YouTube music integration. No real playback assertions here. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const read = name => fs.readFileSync(name, 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(read('music-catalog.js'), sandbox, { filename: 'music-catalog.js' });
const tracks = sandbox.window.__8apdfMusicCatalog;
assert.ok(Array.isArray(tracks), 'Music catalogue must be an array');
assert.equal(tracks.length, 276, 'Unexpected music catalogue size');
const key = song => (song.title + '|' + song.artist).toLowerCase().replace(/[’‘]/g, "'");
assert.equal(new Set(tracks.map(key)).size, tracks.length, 'Music catalogue has duplicate tracks');
const linked = tracks.filter(song => song.videoId);
assert.ok(linked.length >= 49, 'Previously linked songs unexpectedly missing');
assert.ok(linked.every(song => /^[\w-]{11}$/.test(song.videoId)), 'Invalid YouTube video ID');
assert.equal(new Set(linked.map(song => song.videoId)).size, linked.length, 'Duplicate YouTube IDs');
assert.equal(tracks.find(x => x.title === 'Arz Kiya Hai')?.videoId, 'bP8ATWCvqzw');
assert.equal(tracks.find(x => x.title === 'Jo Tum Mere Ho')?.videoId, 'ilNt2bikxDI');
const player = read('music-player.js');
new vm.Script(player, { filename: 'music-player.js' });
const css = read('music-player.css');
const end = player.indexOf('function ensureYouTube()');
const start = player.indexOf('function close(){');
const close = player.slice(start, end);
assert.ok(close.includes("overlay.classList.add('apm-minimized')"), 'Closing library must keep player visible');
assert.ok(close.includes('state.playerReady'), 'Minimization must require ready video');
assert.ok(player.includes('ev.data===p.ENDED'), 'Auto-next listener missing');
assert.ok(player.includes('state.pendingVideoId'), 'Rapid song switch protection missing');
assert.ok(css.includes('#apmOverlay.apm-minimized #apmYTMount iframe'), 'Visible YouTube video dock missing');
assert.ok(css.includes('min-height:200px!important'), 'YouTube player minimum viewport missing');
assert.ok(css.includes('calc(190px + env(safe-area-inset-bottom,0px))'), 'Mobile video safe-area offset missing');
console.log('Music integration regression checks passed:', tracks.length, 'catalogue entries,', linked.length, 'YouTube IDs.');
