const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={};
vm.runInNewContext(fs.readFileSync('shared/title-clarity.js','utf8'),context);
const title=context.__8apdfTitleClarity.display;
assert.equal(title({title:'Ch. 14 was completed in the book &',description:'Chapter 14 was completed in the book (PDF attached) and antonyms were done in module 7'}),'Chapter 14 Completed · Antonyms (Module 7)');
assert.equal(title({title:'Complete Q1 to 8 of Exercise 6.1 find',description:'Complete Q1 to 8 of Exercise 6.1 find'}),'Complete Q1 to 8 of Exercise 6.1');
assert.equal(title({title:'Punjabi poem – ਪਾਠ ਮਾਂ ਦਾ ਸਾਰ'}),'Punjabi poem – ਪਾਠ ਮਾਂ ਦਾ ਸਾਰ');
assert.equal(title({title:'Science Chapter 5 Practice'}),'Science Chapter 5 Practice');
assert.equal(title({title:'Please submit and'}),'Please submit');
assert.equal(title({title:'Hindi test on 5 Nov'}),'Hindi test on 5 Nov');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('title-clarity.css','utf8');
assert(html.includes('/shared/title-clarity.js?'),'Title helper must load before study cards');
assert(html.indexOf('/shared/title-clarity.js?')<html.indexOf('/features/app-core.js?'),'Title helper must initialize before core');
assert(html.includes('/title-clarity.css?'),'Complete-title CSS must load');
assert(css.includes('-webkit-line-clamp:unset!important'),'Card titles must not use line clamps');
assert(css.includes('#announcementGrid .notice-card h3'),'Teacher titles must also remain visible');
console.log('PASS title clarity and unclipped PDF/announcement presentation');
